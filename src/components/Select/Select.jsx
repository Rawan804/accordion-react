import { useId } from "react";
import "./Select.css";

export default function Select({ label, value, options, onChange, numeric = false }) {
  const id = useId();
  return (
    <div className="field">
      <label htmlFor={id}>{label}</label>
      <select id={id} value={value} onChange={(e) => onChange(numeric ? Number(e.target.value) : e.target.value)}>
        {options.map((o) => <option key={o.value} value={o.value}>{o.label}</option>)}
      </select>
    </div>
  );
}
